import { writeFileSync, mkdirSync } from 'node:fs';
import { assess } from '../src/lib/carton-feasibility';
import { CARTON_PHYSICAL_SPECS } from '../src/lib/carton-physical-spec';
import { CARTON_GEOMETRIES } from '../src/lib/carton-geometry';
const dir = 'docs/carton-builder/physical'; mkdirSync(dir, { recursive: true });
const r = (n: number) => Math.round(n * 100) / 100;
const reports = CARTON_PHYSICAL_SPECS.map((s) => {
  const a = assess(s);
  const g = CARTON_GEOMETRIES.find((x) => x.id === s.configId);
  const proportion = g ? {
    visualBodyAspectWidthOverHeight: r(g.body.width / g.body.height),
    physicalFrontFaceAspectLengthOverHeight: r(a.cartonMm[0] / a.cartonMm[2]),
    visualTrayAspect: r(g.tray.width / g.tray.height),
    physicalPrimaryFrontAspect_shortSideFacing: r(s.primary.breadthMm / s.primary.heightMm),
    note: 'The frozen schematic is wider than the physical carton face; unit scale differs between axes. Drawn proportions are illustrative, not dimensional.',
  } : null;
  return { spec: s, assessment: a, proportion };
});
writeFileSync(`${dir}/FEASIBILITY_REPORT.json`, JSON.stringify(reports, null, 2) + '\n');
const f = (n: number) => r(n).toString();
let md = '# Physical feasibility matrix (generated by scripts/report-carton-physical.ts)\n\nAxis-aligned boxes only; carton dimensions are the owner-confirmed **usable internal** dimensions (31 Oct 2026); no wall thickness, tolerance, lid interference or nesting invented.\n';
for (const { spec, assessment: a, proportion } of reports) {
  md += `\n## ${spec.label} (${spec.configId})\n- Carton ${spec.cartonInches.join(' × ')} in = ${a.cartonMm.map(f).join(' × ')} mm (L × B × H); basis: ${spec.dimensionBasis}\n- Primary: ${spec.primary.name}, ${a.primaryMm.join(' × ')} mm; ${a.required} per carton; external stack limit ${spec.maxExternalStackCount} cartons\n- Verdict: **${a.verdict}** (best axis-aligned capacity ${a.bestCapacity}, need ${a.required})\n`;
  if (a.frozenVisual) {
    const v = a.frozenVisual;
    md += `- Frozen visual arrangement (${v.arrangement.columnsAcrossLength} across × ${v.arrangement.rowsAcrossBreadth} deep × ${v.arrangement.levels} levels): needs ${f(v.required.L)} × ${f(v.required.B)} × ${f(v.required.H)} mm; clearance ${f(v.clearanceMm.L)} / ${f(v.clearanceMm.B)} / ${f(v.clearanceMm.H)} mm → **${v.fits ? 'fits (internal dimensions confirmed)' : 'DOES NOT FIT'}**\n`;
    md += `- Tightest axis: ${v.tightest.axis} with ${f(v.tightest.clearanceMm)} mm (${f(v.tightest.percentOfInternal)} % of the internal dimension)\n`;
    if (v.maxWallPerSideIfExternalMm) md += `- Basis not internal: wall thickness per side must stay below ${f(v.maxWallPerSideIfExternalMm.L)} / ${f(v.maxWallPerSideIfExternalMm.B)} / ${f(v.maxWallPerSideIfExternalMm.H)} mm\n`;
  }
  md += '- Orientations (primary dims along L × B × H → boxes along each axis, capacity, slack):\n';
  for (const o of a.allOrientations) md += `  - ${o.orientation.label}: ${o.nx}×${o.ny}×${o.nz} = ${o.capacity}; slack ${f(o.slackMm.L)} / ${f(o.slackMm.B)} / ${f(o.slackMm.H)} mm\n`;
  if (proportion) md += `- Drawn vs physical proportion: schematic body ${proportion.visualBodyAspectWidthOverHeight}:1 vs physical front face ${proportion.physicalFrontFaceAspectLengthOverHeight}:1; schematic tray ${proportion.visualTrayAspect}:1 vs physical primary front ${proportion.physicalPrimaryFrontAspect_shortSideFacing}:1\n`;
  md += `- Open confirmations: ${a.openConfirmations.join('; ')}\n`;
}
writeFileSync(`${dir}/FEASIBILITY_REPORT.md`, md);
console.log('physical report written');
