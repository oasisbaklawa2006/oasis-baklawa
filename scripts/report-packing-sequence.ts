import { writeFileSync, mkdirSync } from 'node:fs';
import { CARTON_GEOMETRIES } from '../src/lib/carton-geometry';
const dir = 'docs/carton-builder/final'; mkdirSync(dir, { recursive: true });
let md = '# Packing-sequence evidence (generated by scripts/report-packing-sequence.ts)\n\nPresentation units; sequence is the renderer insertion order (bottom first, supporting trays before supported trays). Provisional until a pack-and-close trial; 666×6 and 888×4 arrangements are the frozen visual, RTC1×10 is owner-specified.\n';
for (const g of CARTON_GEOMETRIES) {
  const cols = Array.from(new Set(g.slots.map((s) => s.x))).sort((a, b) => a - b);
  md += `\n## ${g.label} (${g.id}) — capacity ${g.capacity}, ${cols.length} column(s), tray ${g.tray.width}×${g.tray.height}, approval: ${g.approval}\n| Step | Slot | Column | Level (from bottom) | x | y |\n|---|---|---|---|---|---|\n`;
  g.insertionOrder.forEach((id, i) => {
    const s = g.slots.find((x) => x.id === id)!;
    md += `| ${i + 1} | ${id} | ${cols.indexOf(s.x) + 1} | ${Math.round((g.floor - s.y) / g.tray.height)} | ${s.x} | ${s.y} |\n`;
  });
  md += `Frames: 1 = empty, 2…${g.capacity + 1} = steps 1…${g.capacity}, ${g.capacity + 2} = closed (contents concealed).\n`;
}
writeFileSync(`${dir}/PACKING_SEQUENCE_EVIDENCE.md`, md);
console.log('written');
